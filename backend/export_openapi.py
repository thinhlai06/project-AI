"""Write docs/architecture/openapi.yaml from the FastAPI app (the code is the source of truth).

Run from the repo root after changing backend/medicheck_server/app.py:

    python -m backend.export_openapi
"""
import os

import yaml

from backend.medicheck_server.app import VerifyRequest, app

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "docs", "architecture", "openapi.yaml")

spec = app.openapi()

# `payload` of /v1/pills/verify is a JSON string inside multipart form data, so FastAPI cannot see its structure:
# publish VerifyRequest (and its nested models) as components and point the form field at it.
req = VerifyRequest.model_json_schema(ref_template="#/components/schemas/{model}")
comps = spec["components"]["schemas"]
comps.update(req.pop("$defs", {}))
comps["VerifyRequest"] = req
body = comps["Body_verify_v1_pills_verify_post"]["properties"]["payload"]
body["description"] = "VerifyRequest serialised as a UTF-8 JSON string (schema: #/components/schemas/VerifyRequest)"
body["contentMediaType"] = "application/json"
body["contentSchema"] = {"$ref": "#/components/schemas/VerifyRequest"}
spec["servers"] = [
    {"url": "http://localhost:8000", "description": "Laptop chạy server (máy giả lập Android dùng http://10.0.2.2:8000)"},
    {"url": "http://{laptop_ip}:8000", "description": "Điện thoại thật cùng mạng Wi-Fi/hotspot với laptop",
     "variables": {"laptop_ip": {"default": "192.168.43.10"}}},
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("# GENERATED by `python -m backend.export_openapi` from backend/medicheck_server/app.py. Do not edit by hand.\n"
            "# Human guide with examples and app notes: backend/API.md\n")
    yaml.safe_dump(spec, f, allow_unicode=True, sort_keys=False, width=120)
print("wrote", OUT)
